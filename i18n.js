let current = 'en';

export function setLanguage(choice) {
    current = choice === 'auto'
        ? (GLib.get_language_names().some(l => l.startsWith('ru')) ? 'ru' : 'en')
        : choice;
}

// Translates a source (English) string into the current language.
export const _ = text => (current === 'ru' && RU[text]) || text;

// Marks a string for translation where it is defined; translate it with _() where it is shown.
export const N_ = text => text;
